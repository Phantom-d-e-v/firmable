"""Per-banner feature extraction.

One Shodan banner (one JSON line) -> one flat row of signals. Pure function, no I/O,
so it parallelises trivially and is easy to unit test. Company-level aggregation and
scoring happen later in DuckDB over the Parquet output.
"""
