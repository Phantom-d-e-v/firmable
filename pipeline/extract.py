# Top-level keys Shodan adds for edge appliances / VPN gateways (prime CVE targets).
EDGE_APPLIANCE_KEYS = ("fortinet", "sonicwall", "checkpoint", "microsoft_exchange",
                       "draytek_vigor", "synology_dsm", "qnap", "hp_ilo")

# Reverse-DNS names generated by ISPs/hosters ("1-2-3-4.static.isp.net", "dsl-pool...").
_PTR_WORDS = re.compile(r"(^|[.-])(static|dynamic|dyn|pool|dsl|adsl|cable|dhcp|customer|cust|"
                        r"broadband|ip|host|client|ppp|fiber|ftth|res|vps|server|srv)[0-9.-]*([.-]|$)")
_DIGITS = re.compile(r"\d+")

WEAK_TLS = {"SSLv2", "SSLv3", "TLSv1", "TLSv1.1"}


def registrable(host: str | None) -> str | None:
    if not host or host[0].isdigit() and host.replace(".", "").isdigit():
        return None
    ext = _TLD(host.lower().strip(".*"))
    return ext.top_domain_under_public_suffix or None


def is_ptr_like(hostname: str, ip: str | None) -> bool:
    h = hostname.lower()
    if ip and "." in ip:
        octets = ip.split(".")
        nums = _DIGITS.findall(h)
        if sum(o in nums for o in octets) >= 3:
            return True
    return bool(_PTR_WORDS.search(h.split(".", 1)[0] if "." in h else h))


def _cert_time(s: str | None) -> datetime | None:
    try:
        return datetime.strptime(s, "%Y%m%d%H%M%SZ").replace(tzinfo=timezone.utc) if s else None
    except ValueError:
        return None


def extract(rec: dict) -> dict:
    sh = rec.get("_shodan") or {}
    module = sh.get("module") or ""
    port = rec.get("port")
    tags = rec.get("tags") or []
    http = rec.get("http") or {}
    ssl = rec.get("ssl") or {}
    cert = ssl.get("cert") or {}
    loc = rec.get("location") or {}
    ts = rec.get("timestamp")

    # --- entity resolution: which company does this service belong to? -------------
    # Strongest evidence first: cert subject / HTTP host are chosen by the owner,
    # PTR-derived hostnames usually describe the hosting provider.
    ip = rec.get("ip_str")
    cand: list[tuple[str, str]] = []
    cn = (cert.get("subject") or {}).get("CN")
    if isinstance(cn, str):
        cand.append(("cert", cn))
    if isinstance(http.get("host"), str):
        cand.append(("http_host", http["host"]))
    cand += [("ptr" if is_ptr_like(h, ip) else "hostname", h) for h in rec.get("hostnames") or []]
    company_domain = domain_source = None
    for src, h in cand:
        d = registrable(h)
        if d and d not in INFRA_DOMAINS:
            company_domain, domain_source = d, src
            break

    # --- vulnerabilities -----------------------------------------------------------
    vulns = rec.get("vulns") or {}
    n_kev = n_verified = 0
    max_cvss = max_epss = 0.0
    kev_cves: list[str] = []
    for cve, v in vulns.items():
        if v.get("kev"):
            n_kev += 1
            kev_cves.append(cve)
        if v.get("verified"):
            n_verified += 1
        max_cvss = max(max_cvss, v.get("cvss") or 0.0)
        max_epss = max(max_epss, v.get("epss") or 0.0)

    # --- TLS -----------------------------------------------------------------------
    expires = _cert_time(cert.get("expires"))
    obs = datetime.fromisoformat(ts).replace(tzinfo=timezone.utc) if ts else None
    days_to_expiry = (expires - obs).days if expires and obs else None
    tls_versions = [v for v in ssl.get("versions") or [] if not v.startswith("-")]

    # --- HTTP / stack ----------------------------------------------------------------
    comps = http.get("components") or {}
    headers = {k.lower() for k in (http.get("headers") or {})}

    exposure = EXPOSURE_BY_MODULE.get(module) or EXPOSURE_BY_PORT.get(port)
    if not exposure and any(k in rec for k in EDGE_APPLIANCE_KEYS):
        exposure = "edge_appliance"

    return {
        "shodan_id": sh.get("id"),
        "ts": ts,
        "ip": ip or rec.get("ipv6"),
        "port": port,
        "transport": rec.get("transport"),
        "module": module,
        "org": rec.get("org"),
        "isp": rec.get("isp"),
        "asn": rec.get("asn"),
        "country": loc.get("country_code"),
        "city": loc.get("city"),
        "company_domain": company_domain,
        "domain_source": domain_source,
        "hostnames": rec.get("hostnames") or [],
        "tags": tags,
        "is_cdn": "cdn" in tags,
        "is_cloud": "cloud" in tags or bool(rec.get("cloud")),
        "is_honeypot": "honeypot" in tags,
        "is_compromised": "compromised" in tags or module in COMPROMISE_MODULES,
        "is_malware_infra": any(h in module for h in MALWARE_MODULE_HINTS),
        "eol_product": "eol-product" in tags,
        "eol_os": "eol-os" in tags,
        "product": rec.get("product"),
        "version": rec.get("version"),
        "os": rec.get("os"),
        "cpe23": rec.get("cpe23") or [],
        "exposure": exposure,
        "n_vulns": len(vulns),
        "n_kev": n_kev,
        "n_verified": n_verified,
        "max_cvss": max_cvss,
        "max_epss": max_epss,
        "kev_cves": kev_cves,
        "has_ssl": bool(ssl),
        "cert_subject_o": (cert.get("subject") or {}).get("O"),
        "cert_expired": cert.get("expired"),
        "cert_days_to_expiry": days_to_expiry,
        "self_signed": "self-signed" in tags,
        "weak_tls": bool(WEAK_TLS.intersection(tls_versions)),
        "http_status": http.get("status"),
        "http_title": (http.get("title") or "")[:200] or None,
        "waf": http.get("waf"),
        "has_securitytxt": bool(http.get("securitytxt")),
        "has_hsts": "strict-transport-security" in headers,
        "has_csp": "content-security-policy" in headers,
        "components": sorted(comps),
        "component_versions": [f"{k}:{v}" for k, m in comps.items() for v in (m.get("versions") or [])],
    }


def extract_line(line: bytes) -> dict | None:
    try:
        return extract(orjson.loads(line))
    except (orjson.JSONDecodeError, TypeError, ValueError):
        return None
